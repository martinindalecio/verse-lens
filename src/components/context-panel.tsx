import type { ReactNode } from "react";
import type { PassageContext } from "@/lib/context-schema";

export type ContextState =
  | { status: "idle" }
  | { status: "loading"; reference: string }
  | { status: "error"; reference: string; message: string }
  | { status: "done"; reference: string; context: PassageContext };

const CONFIDENCE_STYLE = {
  high: "text-emerald-700 dark:text-emerald-400",
  medium: "text-amber-700 dark:text-amber-400",
  low: "text-rose-700 dark:text-rose-400",
} as const;

export function ContextPanel({ state }: { state: ContextState }) {
  if (state.status === "idle") {
    return (
      <p className="text-sm text-muted">
        Tap a verse to select it, tap another to select a range, then ask for its context. Tap inside the selection to clear it.
      </p>
    );
  }
  if (state.status === "loading") {
    return <p className="text-sm text-muted">Gathering context for {state.reference}… this can take a little while.</p>;
  }
  if (state.status === "error") {
    return <p className="text-sm text-rose-700 dark:text-rose-400">{state.message}</p>;
  }

  const c = state.context;
  return (
    <div className="space-y-6 text-sm">
      <div className="space-y-2">
        <h2 className="font-serif text-xl font-semibold">{state.reference}</h2>
        <p>{c.summary}</p>
      </div>

      <Section title="Setting">
        <dl className="grid grid-cols-[auto_1fr] gap-x-3 gap-y-1">
          <Term label="Speaker">{c.setting.speaker}</Term>
          <Term label="Audience">{c.setting.audience}</Term>
          <Term label="Place">{c.setting.place}</Term>
          <Term label="When">{c.setting.when}</Term>
        </dl>
        <Confidence level={c.setting.confidence} />
      </Section>

      <Section title="What's happening around it">
        <p>
          <span className="font-medium">Before: </span>
          {c.narrative_flow.before}
        </p>
        <p>
          <span className="font-medium">After: </span>
          {c.narrative_flow.after}
        </p>
      </Section>

      <Claims title="Historical background" claims={c.historical_context} />
      <Claims title="Culture and customs" claims={c.cultural_context} />

      {c.key_terms.length > 0 && (
        <Section title="Key words">
          <ul className="space-y-2">
            {c.key_terms.map((t) => (
              <li key={t.term + t.transliteration}>
                <span className="font-medium">{t.term}</span>{" "}
                <span className="text-muted">
                  {t.original} ({t.transliteration}
                  {t.strongs && `, ${t.strongs}`})
                </span>
                <p>{t.meaning}</p>
              </li>
            ))}
          </ul>
        </Section>
      )}

      {c.cross_references.length > 0 && (
        <Section title="Cross-references">
          <ul className="space-y-1">
            {c.cross_references.map((r) => (
              <li key={r.reference}>
                <span className="font-medium">{r.reference}</span>: {r.connection}
              </li>
            ))}
          </ul>
        </Section>
      )}

      {c.interpretations.length > 0 && (
        <Section title="How traditions read it" note="Interpretation, not historical fact.">
          <ul className="space-y-2">
            {c.interpretations.map((v) => (
              <li key={v.tradition} className="border-l-2 border-line pl-3">
                <span className="font-medium">{v.tradition}</span>
                <p>{v.view}</p>
              </li>
            ))}
          </ul>
        </Section>
      )}

      {c.open_questions.length > 0 && (
        <Section title="Open questions">
          <ul className="list-disc space-y-1 pl-5">
            {c.open_questions.map((q) => (
              <li key={q}>{q}</li>
            ))}
          </ul>
        </Section>
      )}

      <p className="border-t border-line pt-3 text-xs text-muted">
        AI-generated by Claude. Each claim shows what it rests on and how confident it is. Check important points
        against a study Bible or commentary.
      </p>
    </div>
  );
}

function Section({ title, note, children }: { title: string; note?: string; children: ReactNode }) {
  return (
    <section className="space-y-2">
      <h3 className="text-xs font-semibold uppercase tracking-wide text-muted">
        {title}
        {note && <span className="ml-2 font-normal normal-case tracking-normal italic">{note}</span>}
      </h3>
      {children}
    </section>
  );
}

function Term({ label, children }: { label: string; children: ReactNode }) {
  return (
    <>
      <dt className="text-muted">{label}</dt>
      <dd>{children}</dd>
    </>
  );
}

function Confidence({ level }: { level: keyof typeof CONFIDENCE_STYLE }) {
  return <span className={`text-xs ${CONFIDENCE_STYLE[level]}`}>{level} confidence</span>;
}

function Claims({ title, claims }: { title: string; claims: PassageContext["historical_context"] }) {
  if (claims.length === 0) return null;
  return (
    <Section title={title}>
      <ul className="space-y-3">
        {claims.map((claim) => (
          <li key={claim.text}>
            <p>{claim.text}</p>
            <p className="text-xs text-muted">
              Basis: {claim.basis} · <Confidence level={claim.confidence} />
            </p>
          </li>
        ))}
      </ul>
    </Section>
  );
}
