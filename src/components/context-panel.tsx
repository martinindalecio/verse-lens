import { ReportMistake } from "./report-mistake";
import Link from "next/link";
import type { ReactNode } from "react";
import type { ChapterVerse, PassageContext, PassageContextResponse, PassageData } from "@/lib/context-schema";

export type ContextState =
  | { status: "idle" }
  | { status: "loading"; reference: string }
  | { status: "error"; reference: string; message: string; code?: string; retryAfter?: number }
  | { status: "done"; reference: string; response: PassageContextResponse };

const CONFIDENCE_STYLE = {
  high: "text-emerald-700 dark:text-emerald-400",
  medium: "text-amber-700 dark:text-amber-400",
  low: "text-rose-700 dark:text-rose-400",
} as const;

type Props = {
  state: ContextState;
  /** Opens a person's card at the verse where the passage first names them. */
  onOpenPerson?: (id: string, label: string, verse: ChapterVerse) => void;
};

export function ContextPanel({ state, onOpenPerson }: Props) {
  if (state.status === "idle") {
    return (
      <p className="text-sm text-muted">
        Tap a verse to select it, tap another to select a range, then ask for its context. Tap inside the selection to clear it.
      </p>
    );
  }
  if (state.status === "loading") {
    return <p className="text-sm text-muted">Gathering context for {state.reference}… this can take a little while.</p>;
  }
  if (state.status === "error") {
    if (state.code === "daily_cap_reached") {
      const hours = state.retryAfter ? Math.max(1, Math.round(state.retryAfter / 3600)) : null;
      return (
        <div className="space-y-1 rounded-xl border-2 border-line p-4">
          <p className="font-bold">{state.message}</p>
          <p className="text-sm text-muted">
            Please try this passage again later{hours ? ` (in about ${hours} ${hours === 1 ? "hour" : "hours"})` : ""}. Passages
            someone has already opened still load.
          </p>
        </div>
      );
    }
    return <p className="text-sm text-rose-700 dark:text-rose-400">{state.message}</p>;
  }

  const { unit, selection, ai, data } = state.response;
  return (
    <div className="space-y-6 text-base">
      <UnitHeader response={state.response} />

      <Neighbours data={data} book={unit.book} bookName={unit.bookName} />

      <div className="space-y-6">
        <SourceTag>Written by AI (Claude)</SourceTag>
        <AiSections ai={ai} />
      </div>

      <div className="space-y-6 border-t border-line pt-5">
        <SourceTag>From reference data, not AI</SourceTag>
        <DataSections data={data} onOpenPerson={onOpenPerson} />
      </div>

      <p className="border-t border-line pt-3 text-xs text-muted">
        The explanation covers the whole section {unit.reference}, which holds your selection ({selection.chapter}:
        {selection.start === selection.end ? selection.start : `${selection.start}–${selection.end}`}). It is AI-generated by Claude: each
        claim shows what it rests on and how confident it is. Check important points against a study Bible or commentary.
      </p>
      <ReportMistake target={`passage:${unit.book}.${unit.start[0]}.${unit.start[1]}`} />
    </div>
  );
}

function UnitHeader({ response: { unit, selection } }: { response: PassageContextResponse }) {
  // Within one chapter, every verse of the unit as a small marker with the selection standing
  // out. (A unit crossing chapters doesn't know the earlier chapters' lengths here; it shows the
  // reference only.)
  const crossesChapters = unit.start[0] !== unit.end[0];
  const markers: { v: number; selected: boolean }[] = [];
  if (!crossesChapters) {
    for (let v = unit.start[1]; v <= unit.end[1]; v++) {
      markers.push({ v, selected: unit.start[0] === selection.chapter && v >= selection.start && v <= selection.end });
    }
  }
  return (
    <div className="space-y-2">
      <p className="text-sm font-bold uppercase tracking-wide text-muted">Section (BSB heading)</p>
      <h2 className="text-2xl font-bold">{unit.title}</h2>
      <p className="text-muted">
        {unit.reference}
        {unit.part && ` · part ${unit.part.index} of ${unit.part.count}`}
      </p>
      {markers.length > 0 && (
        <ol className="flex flex-wrap gap-1" aria-label="Verses in this section; your selection is highlighted">
          {markers.map(({ v, selected }) => (
            <li
              key={v}
              aria-current={selected ? "true" : undefined}
              className={`flex h-7 min-w-7 items-center justify-center rounded-md px-1 text-xs tabular-nums ${
                selected ? "bg-accent font-bold text-card" : "bg-chip text-muted"
              }`}
            >
              {v}
            </li>
          ))}
        </ol>
      )}
      <p className="text-sm text-muted">
        Your selection: {selection.chapter}:{selection.start === selection.end ? selection.start : `${selection.start}–${selection.end}`}
        {isOutside(unit.end, selection) && " (it runs past this section; select a later verse to see the next one)"}
      </p>
    </div>
  );
}

const isOutside = (end: ChapterVerse, s: PassageContextResponse["selection"]) => s.chapter > end[0] || (s.chapter === end[0] && s.end > end[1]);

function Neighbours({ data, book, bookName }: { data: PassageData; book: string; bookName: string }) {
  if (!data.before && !data.after) return null;
  return (
    <Section title="What's around it" source="BSB section headings">
      <dl className="grid grid-cols-[auto_1fr] gap-x-3 gap-y-1">
        {data.before && (
          <Term label="Before">
            <Link className="underline" href={`/read/${book}/${data.before.start[0]}?v=${data.before.start[1]}`}>
              {data.before.title}
            </Link>{" "}
            <span className="text-muted">
              ({bookName} {data.before.reference})
            </span>
          </Term>
        )}
        {data.after && (
          <Term label="After">
            <Link className="underline" href={`/read/${book}/${data.after.start[0]}?v=${data.after.start[1]}`}>
              {data.after.title}
            </Link>{" "}
            <span className="text-muted">
              ({bookName} {data.after.reference})
            </span>
          </Term>
        )}
      </dl>
    </Section>
  );
}

function AiSections({ ai: c }: { ai: PassageContext }) {
  return (
    <>
      <p>{c.summary}</p>

      <Section title="Setting">
        <dl className="grid grid-cols-[auto_1fr] gap-x-3 gap-y-1">
          <Term label="Speaker">{c.setting.speaker}</Term>
          <Term label="Audience">{c.setting.audience}</Term>
          <Term label="Place">{c.setting.place}</Term>
          <Term label="When">{c.setting.when}</Term>
        </dl>
        <Confidence level={c.setting.confidence} />
      </Section>

      <Claims title="Historical background" claims={c.historical_context} />
      <Claims title="Culture and customs" claims={c.cultural_context} />

      {c.interpretations.length > 0 && (
        <Section title="How traditions read it" note="Interpretation, not historical fact.">
          <ul className="space-y-2">
            {c.interpretations.map((v) => (
              <li key={v.tradition} className="border-l-2 border-line pl-3">
                <span className="font-medium">{v.tradition}</span>
                <p>{v.view}</p>
              </li>
            ))}
          </ul>
        </Section>
      )}

      {c.open_questions.length > 0 && (
        <Section title="Open questions">
          <ul className="list-disc space-y-1 pl-5">
            {c.open_questions.map((q) => (
              <li key={q}>{q}</li>
            ))}
          </ul>
        </Section>
      )}
    </>
  );
}

function DataSections({ data, onOpenPerson }: { data: PassageData; onOpenPerson?: Props["onOpenPerson"] }) {
  const bsb = data.crossReferences.filter((r) => r.source === "bsb");
  const open = data.crossReferences.filter((r) => r.source === "openbible");
  return (
    <>
      {data.people.length > 0 && (
        <Section title="People in this section" source="STEPBible TIPNR, CC BY 4.0; descriptions written by AI for STEPBible">
          <ul className="space-y-2">
            {data.people.map((p) => (
              <li key={p.id}>
                {onOpenPerson ? (
                  <button type="button" className="font-medium underline" onClick={() => onOpenPerson(p.id, p.name, p.first)}>
                    {p.name}
                  </button>
                ) : (
                  <span className="font-medium">{p.name}</span>
                )}
                {p.usualName && <span className="text-muted"> (also called {p.usualName})</span>}
                {p.description && <span>: {p.description}</span>} <span className="text-sm text-muted">{p.firstRef}</span>
              </li>
            ))}
          </ul>
        </Section>
      )}

      {bsb.length > 0 && (
        <Section title="Parallel passages" source="BSB section headings">
          <RefList refs={bsb} />
        </Section>
      )}
      {open.length > 0 && (
        <Section title="Cross references" source="OpenBible.info, CC BY">
          <RefList refs={open} />
        </Section>
      )}

      {data.keyTerms.length > 0 && (
        <Section title="Key words" source="STEPBible TAGNT/TAHOT, CC BY 4.0">
          <ul className="space-y-1">
            {data.keyTerms.map((t) => (
              <li key={t.strongs}>
                <span className="font-medium" lang={t.strongs.startsWith("G") ? "grc" : "hbo"}>
                  {t.lemma}
                </span>{" "}
                <span className="text-muted">
                  ({t.translit}, {t.strongs})
                </span>
                : {t.gloss}
                {t.count > 1 && <span className="text-sm text-muted"> · {t.count}×</span>}
              </li>
            ))}
          </ul>
        </Section>
      )}
    </>
  );
}

function RefList({ refs }: { refs: PassageData["crossReferences"] }) {
  return (
    <ul className="flex flex-wrap gap-2">
      {refs.map((r) => (
        <li key={r.label}>
          {r.to ? (
            <Link href={`/read/${r.to.book}/${r.to.chapter}?v=${r.to.verse}`} className="inline-flex min-h-11 items-center rounded-full bg-chip px-4 font-medium">
              {r.label}
            </Link>
          ) : (
            <span className="inline-flex min-h-11 items-center rounded-full bg-chip px-4">{r.label}</span>
          )}
        </li>
      ))}
    </ul>
  );
}

function SourceTag({ children }: { children: ReactNode }) {
  return <p className="inline-block rounded-full border border-line px-3 py-1 text-xs font-bold uppercase tracking-wide text-muted">{children}</p>;
}

function Section({ title, note, source, children }: { title: string; note?: string; source?: string; children: ReactNode }) {
  return (
    <section className="space-y-2">
      <h3 className="text-lg font-bold">
        {title}
        {note && <span className="ml-2 font-normal normal-case tracking-normal italic">{note}</span>}
      </h3>
      {source && <p className="-mt-1 text-xs text-muted">Source: {source}</p>}
      {children}
    </section>
  );
}

function Term({ label, children }: { label: string; children: ReactNode }) {
  return (
    <>
      <dt className="text-muted">{label}</dt>
      <dd>{children}</dd>
    </>
  );
}

function Confidence({ level }: { level: keyof typeof CONFIDENCE_STYLE }) {
  return <span className={`text-xs ${CONFIDENCE_STYLE[level]}`}>{level} confidence</span>;
}

function Claims({ title, claims }: { title: string; claims: PassageContext["historical_context"] }) {
  if (claims.length === 0) return null;
  return (
    <Section title={title}>
      <ul className="space-y-3">
        {claims.map((claim) => (
          <li key={claim.text}>
            <p>{claim.text}</p>
            <p className="text-xs text-muted">
              Basis: {claim.basis} · <Confidence level={claim.confidence} />
            </p>
          </li>
        ))}
      </ul>
    </Section>
  );
}
