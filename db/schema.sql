-- Verse Lens database schema (Postgres; hosted on Neon).
-- Plan: docs/designs/reading-companion.md. Spanish-ready: anything with words in it is keyed
-- by language and Bible translation.
--
-- Clients (web today, iOS/Android later) never connect to the database directly; they go
-- through the app's API routes, which hold DATABASE_URL.

-- People (reference data, loaded by scripts from STEPBible TIPNR, CC BY 4.0) ---------------

create table if not exists people (
  id          text primary key,              -- TIPNR unique name, e.g. 'Paul@Act.7.58-2Pe'
  strong      text not null,                 -- TIPNR unified Strong's number
  name        text not null,                 -- most common English form, e.g. 'Paul'
  kind        text not null,                 -- 'Male' | 'Female' | 'Divine'
  description text not null default '',      -- e.g. 'Apostle living at the time of the New Testament'
  tribe       text not null default ''
);

-- Name forms per translation ('Saul', 'Paul'; later 'Saulo', 'Pablo').
create table if not exists person_names (
  person_id   text not null references people(id) on delete cascade,
  lang        text not null,                 -- 'en', 'es'
  translation text not null,                 -- 'bsb', 'vbl', 'rv1909', ...
  form        text not null,
  primary key (person_id, translation, form)
);

-- Family links from TIPNR (fact, not AI).
create table if not exists relationships (
  person_id   text not null references people(id) on delete cascade,
  related_id  text not null,                 -- may name someone outside the people table
  relation    text not null,                 -- 'parent' | 'sibling' | 'partner' | 'child'
  source      text not null default 'tipnr', -- 'tipnr' | 'override'
  primary key (person_id, related_id, relation)
);

-- Where each person's name appears in a translation's text.
create table if not exists person_mentions (
  translation text not null,
  book        text not null,                 -- book slug, e.g. 'acts'
  chapter     int  not null,
  verse       int  not null,
  start_char  int  not null,
  end_char    int  not null,
  person_id   text not null references people(id) on delete cascade,
  inferred    boolean not null default false, -- true: filled from chapter context, not a TIPNR reference
  primary key (translation, book, chapter, verse, start_char)
);
create index if not exists person_mentions_person on person_mentions (person_id, translation, book, chapter, verse);

-- Episodes: runs of consecutive appearances, for the "so far" timeline.
create table if not exists episodes (
  id          bigint generated always as identity primary key,
  person_id   text not null references people(id) on delete cascade,
  book        text not null,
  start_ch    int  not null,
  start_v     int  not null,
  end_ch      int  not null,
  end_v       int  not null,
  unique (person_id, book, start_ch, start_v)
);

-- Text with words in it: descriptions, AI summaries. Always labeled with where it came from.
create table if not exists person_texts (
  person_id      text not null references people(id) on delete cascade,
  lang           text not null,
  kind           text not null,              -- 'briefest' | 'brief' | 'short' | 'why' | 'episode:<id>'
  body           text not null,
  source         text not null,              -- 'tipnr-ai' (TIPNR text adapted from AI) | 'claude' | 'human'
  prompt_version int,
  created_at     timestamptz not null default now(),
  primary key (person_id, lang, kind)
);

-- Relationships beyond family, generated by AI and shown as such.
create table if not exists ai_relationships (
  person_id      text not null references people(id) on delete cascade,
  related_id     text not null references people(id) on delete cascade,
  lang           text not null,
  label          text not null,              -- 'vouched for him'
  basis_ref      text not null,              -- verse the relationship rests on, e.g. 'acts 9:27'
  confidence     text not null check (confidence in ('high', 'medium', 'low')),
  prompt_version int  not null,
  created_at     timestamptz not null default now(),
  primary key (person_id, related_id, lang)
);

-- Passage explanations (replaces the in-memory cache in src/lib/context.ts) ----------------

create table if not exists passage_context (
  lang           text not null,
  translation    text not null,
  book           text not null,
  chapter        int  not null,
  start_v        int  not null,
  end_v          int  not null,
  prompt_version int  not null,
  context        jsonb not null,             -- PassageContextSchema
  created_at     timestamptz not null default now(),
  primary key (lang, translation, book, chapter, start_v, end_v, prompt_version)
);

-- Per user (phase 3; user ids come from the auth provider) ---------------------------------

create table if not exists reading_positions (
  user_id     text not null,
  device      text not null,                 -- 'iphone', 'laptop', ...
  translation text not null,
  book        text not null,
  chapter     int  not null,
  verse       int  not null,
  updated_at  timestamptz not null default now(),
  primary key (user_id, device)
);

-- Reports from "Report a mistake" on cards and passages.
create table if not exists mistake_reports (
  id          bigint generated always as identity primary key,
  user_id     text,                          -- null when signed out
  target      text not null,                 -- 'person:<id>' or 'passage:<book>.<ch>.<v>-<v>'
  lang        text not null,
  message     text not null,
  created_at  timestamptz not null default now(),
  resolved    boolean not null default false
);
